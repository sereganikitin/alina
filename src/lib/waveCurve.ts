/**
 * Кривая шва между секциями — точная форма «нашей волны», присланная как
 * волна.svg (экспорт из CorelDRAW, исходный viewBox 0 0 1909.99 32.18).
 * Сохранена отдельно, чтобы переиспользовать в других швах между блоками
 * (не только Hero→Обо мне) без повторной оцифровки кривой.
 */
export const WAVE_CURVE_WIDTH = 1909.99;

/** Натуральный вертикальный размах кривой в исходном viewBox (32.18 — но
 *  контрольные точки уходят чуть выше/ниже, реальный размах ~52.5). */
export const WAVE_CURVE_NATURAL_HEIGHT = 32.18;

/**
 * Путь кривой (абсолютные координаты, Y смещён на +offsetY относительно
 * исходного волна.svg — чтобы кривая не уходила в отрицательные Y и её
 * удобно было класть в SVG-паттерн произвольной высоты). При offsetY=0
 * координаты Y соответствуют исходному файлу один в один.
 */
export function waveCurvePath(offsetY: number): string {
  const p0y = 19.33 + offsetY;
  const c1y = 2.39 + offsetY;
  const c2y = -10.37 + offsetY;
  const p1y = 16.48 + offsetY;
  const c3y = 42.17 + offsetY;
  const c4y = 28.96 + offsetY;
  const p2y = 16.48 + offsetY;
  return `M0.05,${p0y} C314.55,${c1y} 575.71,${c2y} 999.51,${p1y} 1404.92,${c3y} 1624.4,${c4y} 1909.95,${p2y}`;
}
