export function updateLegacyContent(content, article) {
  content ??= {};
  if (content.novemberRevision) return content;

  const existingPosts = content.blog?.posts ?? [];
  const lowerInitial = (text) => text.replace(/^[А-ЯЁ](?=[а-яё])/, (letter) => letter.toLowerCase());
  const sun = content.principles?.sun?.map(({ title, items }) => {
    const updated = items.map(lowerInitial);
    if (/^отношения с собой$/i.test(title) && !updated.some((item) => /нейроотлич/i.test(item))) {
      updated.push("нейроотличия");
    }
    if (/^травматический опыт и утрата$/i.test(title) && !updated.some((item) => /послеродов/i.test(item))) {
      const index = updated.findIndex((item) => /^травматический опыт \(/i.test(item));
      if (index !== -1) updated[index] = updated[index].replace(" и другие события", ", роды/послеродовый период и другие события");
    }
    return { title: lowerInitial(title), items: updated };
  });
  const exclusions = content.principles?.notWithWhom;

  return {
    ...content,
    novemberRevision: true,
    about: { ...content.about, lead: aboutBeforePrinciples, afterPrinciples: aboutAfterPrinciples },
    approach: { ...content.approach, ...novemberApproach, paragraphs: [] },
    education: { ...content.education, diplomas, lead: "" },
    principles: {
      ...content.principles,
      sun,
      notWithWhom: exclusions && !/игровыми/i.test(exclusions)
        ? exclusions.replace(/химическими зависимостями/i, "химическими и игровыми зависимостями")
        : exclusions,
      side: novemberExpectations,
    },
    consultation: { ...content.consultation, ...novemberConsultation },
    faq: novemberFaq,
    funFacts: { ...content.funFacts, title: "Интересное обо мне", items: factItems },
    blog: { ...content.blog, posts: existingPosts.some((post) => post.slug === article.slug) ? existingPosts : [article, ...existingPosts] },
  };
}
