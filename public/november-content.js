export function applyEditorialUpdates(content) {
  const items = content.funFacts.items.flatMap((item) => {
    const stock = item.stock ?? /^\/photos\/facts\/(dance|japan|psychology)\.jpg$/.test(item.image);
    const [psychology, professions] = item.text.split(/\r?\n\s*…другие профессии\s*\r?\n/i);
    if (item.title?.toLowerCase() === "психология и…" && professions) {
      return [
        { ...item, text: psychology.trim(), stock },
        { title: "…другие профессии", text: professions.trim(), image: "", stock: false },
      ];
    }
    return [{ ...item, stock }];
  });
  const faq = content.faq.map((item) => {
    const isHtml = /<[a-z][\s\S]*>/i.test(item.a);
    const paragraphBreak = isHtml ? "</p><p>" : "\n\n";
    const answer = item.a
      .replace(/(?:<br\s*\/?>|\r?\n)\s*(?=Детали обсуждаются)/i, paragraphBreak)
      .replace(/\.\s+(?=Любые затруднения|Здесь из неясной проблемы|Регулярно прохожу)/g, paragraphBreak)
      .replace(/\.(?=\s*(?:<\/p>|$))/g, "");
    return { ...item, a: answer };
  });
  const diplomas = content.education.diplomas.map((diploma) => {
    if ((diploma.number || diploma.num) !== "3.1") return diploma;
    return { ...diploma, title: diploma.title.replace(/конференции(?= повышени)/i, "$& и") };
  });
  return {
    ...content,
    education: { ...content.education, diplomas },
    faq,
    faqImage: content.faqImage === "/media/-4-6675d975.jpg" ? "/photos/faq-alina.webp" : content.faqImage,
    funFacts: { ...content.funFacts, items },
    principles: {
      ...content.principles,
      notWithWhom: content.principles.notWithWhom?.replace(/\.(?=\s*(?:<\/p>)?\s*$)/, ""),
    },
  };
}
